"""
ai_state.py — Глобальный флаг доступности ИИ-аналитики (GigaChat).

Механика:
 1. При запуске бота (main.py) выполняется тестовый запрос к API GigaChat.
 2. Если тест прошёл успешно — AI_AVAILABLE = True и в чеках показывается
    настоящий ИИ-вердикт от нейронки.
 3. Если при тесте произошла любая ошибка — AI_AVAILABLE = False и ИИ-аналитика
    просто НЕ используется: в чеке будет только математический расчёт выгоды,
    без текста от нейросети.

Флаг можно переключать на лету из хэндлеров (например, если реальный запрос
к нейронке упал — автоматически отключить ИИ до следующего перезапуска бота).
"""

# По умолчанию ИИ выключен: вердикт будет добавлен в чек только после
# успешного теста при запуске бота.
AI_AVAILABLE: bool = False


def set_ai_available(available: bool) -> None:
    """Устанавливает глобальный флаг доступности ИИ-аналитики."""
    global AI_AVAILABLE
    AI_AVAILABLE = available


def is_ai_available() -> bool:
    """Возвращает текущее состояние флага доступности ИИ-аналитики."""
    return AI_AVAILABLE
